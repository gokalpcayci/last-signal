// Share image (Open Graph / Twitter card): public/og.png, 1200×630, dark LED style.
// Draws an HTML card (LED inkblot from src/brand/ledCells.ts, Daktilo title, one LED per object
// in status colours) and screenshots it with headless Chrome.
//   bun scripts/build_og.mjs
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'

// LED grid of the mark (generated by build_brand_variants.py)
const src = readFileSync(join(root, 'src/brand/ledCells.ts'), 'utf8')
const grids = JSON.parse(src.slice(src.indexOf('= {') + 2).replace(/;\s*$/, ''))

// one LED per object, in status colours, counted from the data files
const statuses = ['hardware', 'mars', 'deepspace'].flatMap((f) =>
  [...readFileSync(join(root, `src/data/${f}.ts`), 'utf8').matchAll(/status: '(active|silent)'/g)].map((m) => m[1]))
const active = statuses.filter((s) => s === 'active').length
const leds = [...Array(active).fill('active'), ...Array(statuses.length - active).fill('silent')]

const font = (w, file) => `@font-face{font-family:Daktilo;font-weight:${w};src:url('file://${root}/public/fonts/${file}') format('woff')}`

const html = `<!doctype html><html><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;500;700&display=block" rel="stylesheet">
<style>
${font(400, 'Daktilo-Regular.woff')}${font(700, 'Daktilo-Bold.woff')}
*{margin:0;box-sizing:border-box}
html,body{width:1200px;height:630px;background:#0d0e0d;color:#e6e6df;overflow:hidden}
body{position:relative;font-family:'JetBrains Mono',monospace}
.grid{position:absolute;inset:40px 48px;border:1px dashed rgba(255,255,255,.10)}
.grid i{position:absolute;border:0 dashed rgba(255,255,255,.07)}
.lab{position:absolute;font-size:12px;letter-spacing:.12em;color:#3d3f3a}
canvas{position:absolute;left:70px;top:160px}
.copy{position:absolute;left:600px;top:118px;width:540px}
.tag{font-size:14px;letter-spacing:.16em;color:#6e706a;margin-bottom:22px}
.tag b{color:#5fd068;font-weight:500}
h1{font-family:Daktilo;font-weight:700;font-size:78px;line-height:.95;letter-spacing:-.05em}
p{margin-top:24px;font-size:19px;line-height:1.45;color:#c9cbc3;max-width:500px}
.leds{display:flex;gap:4px;margin-top:28px}
.leds span{width:7px;height:7px;border-radius:50%}
.active{background:#5fd068;box-shadow:0 0 6px rgba(95,208,104,.7)}
.silent{background:#e56b47;opacity:.85}
.key{margin-top:14px;font-size:13px;letter-spacing:.12em;color:#6e706a}
.key em{font-style:normal;color:#5fd068}.key u{text-decoration:none;color:#e56b47}
.url{position:absolute;left:600px;bottom:58px;font-size:15px;letter-spacing:.2em;color:#e6e6df}
.url span{color:#6e706a}
</style></head><body>
<div class="grid" id="grid"></div>
<canvas id="c" width="960" height="680" style="width:480px;height:340px"></canvas>
<div class="copy">
  <div class="tag">[<b>&#9679;</b> SIGNAL] MOON · MARS · DEEP SPACE</div>
  <h1>LAST<br>SIGNAL</h1>
  <p>Every machine NASA left behind, on one mission-control map. Which ones are still talking?</p>
  <div class="leds">${leds.map((s) => `<span class="${s}"></span>`).join('')}</div>
  <div class="key"><em>${active} STILL TALKING</em> · <u>${leds.length - active} GONE SILENT</u></div>
</div>
<div class="url">LASTSIGNAL.EARTH <span>/ NASA SPACE APPS</span></div>
<script>
// dashed A–F / 1–5 grid like the dashboard
const g = document.getElementById('grid'), W = 1104, H = 550
for (let i = 1; i < 6; i++) { const e = document.createElement('i'); e.style.cssText = 'left:'+(W*i/6)+'px;top:0;bottom:0;border-left-width:1px'; g.appendChild(e) }
for (let i = 1; i < 5; i++) { const e = document.createElement('i'); e.style.cssText = 'top:'+(H*i/5)+'px;left:0;right:0;border-top-width:1px'; g.appendChild(e) }
'ABCDEF'.split('').forEach((c, i) => { const l = document.createElement('div'); l.className = 'lab'; l.textContent = c; l.style.cssText = 'left:'+(48+W*(i+.5)/6-4)+'px;top:18px'; document.body.appendChild(l) })
for (let i = 0; i < 5; i++) { const l = document.createElement('div'); l.className = 'lab'; l.textContent = i+1; l.style.cssText = 'left:24px;top:'+(40+H*(i+.5)/5-8)+'px'; document.body.appendChild(l) }

// LED inkblot: ghost LEDs over the whole panel, lit cells by depth, one green signal LED
const grid = ${JSON.stringify(grids.fine)}
const c = document.getElementById('c'), x = c.getContext('2d'), S = 2
const [vx, vy, vw, vh] = grid.viewBox, k = (c.width / S) / vw, step = grid.step * k
const lit = new Map()
for (let i = 0; i < grid.cells.length; i += 3) lit.set(Math.round((grid.cells[i]-vx)/grid.step)+','+Math.round((grid.cells[i+1]-vy)/grid.step), grid.cells[i+2])
const cols = Math.floor(vw / grid.step), rows = Math.floor(vh / grid.step)
const off = (grid.cells[0]-vx) % grid.step, offy = (grid.cells[1]-vy) % grid.step
const r = step * 0.36
let best = null, bestD = -1
for (let j = 0; j < rows; j++) for (let i = 0; i < cols; i++) {
  const d = lit.get(i+','+j)
  const cx = (off + i*grid.step) * k * S, cy = (offy + j*grid.step) * k * S
  x.beginPath(); x.arc(cx, cy, r*S, 0, 7)
  if (d === undefined) { x.fillStyle = 'rgba(230,230,223,0.07)' }
  else { const a = 0.35 + 0.65 * Math.min(1, d / 60); x.fillStyle = 'rgba(230,230,223,'+a.toFixed(3)+')'; if (d > bestD && j > rows*0.55) { bestD = d; best = [cx, cy] } }
  x.fill()
}
if (best) { x.shadowColor = '#5fd068'; x.shadowBlur = 14*S; x.fillStyle = '#5fd068'; x.beginPath(); x.arc(best[0], best[1], r*S, 0, 7); x.fill() }
</script></body></html>`

const dir = mkdtempSync(join(tmpdir(), 'og-'))
const page = join(dir, 'og.html')
writeFileSync(page, html)
const out = join(root, 'public/og.png')
execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--allow-file-access-from-files',
  '--force-device-scale-factor=1', '--window-size=1200,630', '--virtual-time-budget=4000',
  `--screenshot=${out}`, `file://${page}`], { stdio: 'inherit' })
console.log(`wrote ${out} (${leds.length} objects, ${active} active)`)
